def test_init_sql_makes_the_roles_then_the_database_then_its_schemas(tree: Path) -> None:
    text = init_sql_text(Workspace.load(tree))
    assert text.startswith("-- GENERATED by ledger-devtools sync")
    cluster, _, schemas = text.partition("CREATE DATABASE ledger;\n\\connect ledger\n")
    assert schemas
    for role in ("ledger_relay", "ledger_app", "ledger_migrator"):
        assert f'CREATE ROLE "{role}"' in cluster
    for role in ("platform_owner", "platform_rw", "platform_purge", "identity_owner", "identity_rw"):
        assert f'CREATE ROLE "{role}"' in cluster
        assert f'CREATE ROLE "{role}"' not in schemas
    assert 'GRANT "identity_rw" TO "ledger_app"' in cluster
    assert 'CREATE ROLE "ledger_signer"' not in text
    assert 'CREATE SCHEMA IF NOT EXISTS "platform" AUTHORIZATION "platform_owner";' in schemas
    assert schemas.index('"platform" AUTHORIZATION') < schemas.index('"identity" AUTHORIZATION')
    roles = tuple(SchemaRoles(schema=schema) for schema in ("platform", "identity"))
    for statement in cluster_statements(roles, LOCAL_LOGINS, salt=local_salt):
        assert f"{statement};\n" in cluster
    for statement in database_statements(roles):
        assert f"{statement};\n" in schemas


def test_init_sql_holds_verifiers_never_the_passwords(tree: Path) -> None:
    text = init_sql_text(Workspace.load(tree))
    passwords = text.split("PASSWORD ")[1:]
    assert passwords
    assert all(password.startswith(("E'SCRAM-SHA-256$4096:", "NULL")) for password in passwords)
    assert sum(password.startswith("E'SCRAM") for password in passwords) == 2  # ledger_app, ledger_migrator


def test_init_sql_is_the_same_at_every_sync(tree: Path) -> None:
    workspace = Workspace.load(tree)
    assert init_sql_text(workspace) == init_sql_text(workspace)


def test_the_local_salt_is_fixed_per_login_and_as_long_as_postgres_own() -> None:
    assert local_salt("ledger_app") == local_salt("ledger_app")
    assert local_salt("ledger_app") != local_salt("ledger_migrator")
    assert len(local_salt("ledger_app")) == SALT_BYTES


def test_a_channel_s_schema_gets_its_roles_too(tree: Path, write: Writer) -> None:
    write("countries/do", COUNTRY, ())
    text = init_sql_text(Workspace.load(tree))
    assert 'CREATE ROLE "do_ecf_owner"' in text
    assert 'CREATE ROLE "do_ecf_rw"' in text
    assert 'CREATE SCHEMA IF NOT EXISTS "do_ecf" AUTHORIZATION "do_ecf_owner";' in text


def isolated(name: str, *, isolated_in: str | None) -> str:
    """A module owning schema ``name``, isolated in ``isolated_in``'s role if one is given."""
    isolation = "" if isolated_in is None else f'isolated_in = "{isolated_in}"\n'
    return (
        f'[package]\nname = "{name}"\nkind = "module"\nsummary = "A module."\nowners = ["@o"]\n'
        f'[dependencies]\npackages = ["kernel", "platform"]\n[data]\nschema = "{name}"\n{isolation}'
    )


def test_an_isolated_schema_belongs_to_the_signer_login(tree: Path, write: Writer) -> None:
    write("modules/vault", isolated("vault", isolated_in="signer"), ())
    text = init_sql_text(Workspace.load(tree))
    assert 'GRANT "vault_rw" TO "ledger_signer"' in text
    assert 'GRANT "vault_purge" TO "ledger_signer"' in text
    assert 'GRANT "vault_rw" TO "ledger_app"' not in text
    assert 'GRANT "identity_rw" TO "ledger_app"' in text
    assert 'GRANT "platform_rw" TO "ledger_signer"' in text  # schedule leases
    assert 'CREATE ROLE "ledger_signer"' in text


def test_a_schema_named_signer_is_not_isolated_by_its_name(tree: Path, write: Writer) -> None:
    write("modules/signer", isolated("signer", isolated_in=None), ())
    text = init_sql_text(Workspace.load(tree))
    assert 'GRANT "signer_rw" TO "ledger_app"' in text
    assert 'CREATE ROLE "ledger_signer"' not in text
