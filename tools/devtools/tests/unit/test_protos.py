def test_a_proto_outside_the_layout_is_a_problem(tree: Path, vault: Path) -> None:
    del vault
    plant(
        tree,
        {
            "vault.proto": TYPES,
            "ledger/vault/types.proto": TYPES,
            "ledger/vault/v1/Types.proto": TYPES,
            "ledger/vault/v1/notes.txt": "not a contract",
        },
    )
    rule = "a contract is contracts/proto/ledger/<module>/v<N>/<name>.proto, its names in snake_case (§4.4)"
    assert proto_problems(Workspace.load(tree)) == (
        Problem("contracts/proto/ledger/vault/types.proto", rule),
        Problem("contracts/proto/ledger/vault/v1/Types.proto", rule),
        Problem("contracts/proto/vault.proto", rule),
    )


def test_a_proto_protoc_cannot_compile_is_a_problem_with_protoc_s_reason(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/types.proto": TYPES.replace("KIND_SEALED = 1;", "KIND_SEALED = 1")})
    (problem,) = proto_problems(Workspace.load(tree))
    assert problem.where == "contracts/proto/ledger/vault/v1/types.proto"
    assert problem.message.startswith("protoc refuses it: ledger/vault/v1/types.proto:")
    assert 'Expected ";"' in problem.message
    assert str(tree) not in problem.message
    with pytest.raises(
        protos.ProtocFailedError, match=r"protoc could not generate the gRPC code: ledger/vault"
    ):
        generated(tree)


def test_contracts_that_conflict_are_problems_of_one_protoc_run(tree: Path, vault: Path) -> None:
    del vault
    ping = 'syntax = "proto3";\n\npackage ledger.vault.v1;\n\nmessage Ping {\n  string id = 1;\n}\n'
    plant(tree, {"ledger/vault/v1/a.proto": ping, "ledger/vault/v1/b.proto": ping})
    problems = proto_problems(Workspace.load(tree))
    assert [problem.where for problem in problems] == ["contracts/proto/ledger/vault/v1/b.proto"]
    assert (
        '"ledger.vault.v1.Ping" is already defined in file "ledger/vault/v1/a.proto"' in problems[0].message
    )


