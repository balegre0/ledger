def test_nothing_is_generated_and_nothing_wrong_without_a_proto(tree: Path, vault: Path) -> None:
    del vault
    assert generated(tree) == {}
    assert proto_problems(Workspace.load(tree)) == ()


def test_a_proto_of_a_missing_module_is_a_problem(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/ghost/v1/ghost.proto": TYPES.replace("ledger.vault.v1", "ledger.ghost.v1")})
    assert proto_problems(Workspace.load(tree)) == (
        Problem(
            "contracts/proto/ledger/ghost/v1/ghost.proto",
            "no module 'ghost' (modules/ghost/manifest.toml) to generate its gRPC code into",
        ),
    )
    assert generated(tree) == {}


def test_a_package_that_does_not_match_its_path_is_a_problem(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/types.proto": TYPES.replace("ledger.vault.v1", "ledger.vault.v2")})
    assert proto_problems(Workspace.load(tree)) == (
        Problem(
            "contracts/proto/ledger/vault/v1/types.proto",
            "declares package 'ledger.vault.v2', not 'ledger.vault.v1', which its path names",
        ),
    )


def test_a_proto_outside_the_layout_is_a_problem(tree: Path, vault: Path) -> None:
    del vault
    plant(
        tree,
        {
            "vault.proto": TYPES,
            "ledger/vault/types.proto": TYPES,
            "ledger/vault/v1/Types.proto": TYPES,
            "ledger/vault/v1/notes.txt": "not a contract",
        },
    )
    rule = "a contract is contracts/proto/ledger/<module>/v<N>/<name>.proto, its names in snake_case (§4.4)"
    assert proto_problems(Workspace.load(tree)) == (
        Problem("contracts/proto/ledger/vault/types.proto", rule),
        Problem("contracts/proto/ledger/vault/v1/Types.proto", rule),
        Problem("contracts/proto/vault.proto", rule),
    )


def test_a_proto_protoc_cannot_compile_is_a_problem(tree: Path, vault: Path) -> None:
    """protoc says why on the process's standard error (C's, flushed at exit): no capture sees it here."""
    del vault
    plant(tree, {"ledger/vault/v1/types.proto": TYPES.replace("KIND_SEALED = 1;", "KIND_SEALED = 1")})
    assert proto_problems(Workspace.load(tree)) == (
        Problem(
            "contracts/proto/ledger/vault/v1/types.proto",
            "protoc cannot compile it (it says why on standard error, as does `uv run poe proto-lint`)",
        ),
    )
    with pytest.raises(
        ProtocFailedError, match=r"contracts/proto/ledger/vault/v1/types\.proto \(it says why"
    ):
        generated(tree)


def test_without_protoc_nothing_is_generated(
    tree: Path, vault: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/types.proto": TYPES})
    monkeypatch.setattr(
        protos, "_PROTOC", EntryPoint(name="protoc", value="grpc_tools.protoc:__name__", group="test")
    )
    with pytest.raises(ProtocUnavailableError, match="grpcio-tools provides no protoc"):
        generated(tree)


def test_two_versions_that_generate_one_file_are_a_problem(tree: Path, vault: Path) -> None:
    del vault
    plant(
        tree,
        {
            "ledger/vault/v1/types.proto": TYPES,
            "ledger/vault/v2/types.proto": TYPES.replace("ledger.vault.v1", "ledger.vault.v2"),
        },
    )
    assert proto_problems(Workspace.load(tree)) == (
        Problem(
            "contracts/proto/ledger/vault/v2/types.proto",
            (
                "generates the files contracts/proto/ledger/vault/v1/types.proto generates: "
                "a module's gRPC code is one package"
            ),
        ),
    )
