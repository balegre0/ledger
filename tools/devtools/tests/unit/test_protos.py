def test_two_versions_of_one_contract_live_side_by_side(tree: Path, vault: Path) -> None:
    del vault
    plant(
        tree,
        {
            **CONTRACTS,
            "ledger/vault/v2/vault.proto": V2_SERVICE,
            "ledger/vault/v2/types.proto": TYPES.replace("ledger.vault.v1", "ledger.vault.v2"),
        },
    )
    assert proto_problems(Workspace.load(tree)) == ()
    files = generated(tree)
    v2 = PACKAGE / "v2"
    assert {V1 / "vault_pb2.py", v2 / "vault_pb2.py", v2 / "types_pb2.py", v2 / "__init__.py"} <= set(files)
    assert b"from ledger_vault.adapters.grpc._generated.v1 import types_pb2 as " in files[v2 / "vault_pb2.py"]
    assert b"from ledger_vault.adapters.grpc._generated.v2 import types_pb2 as " in files[v2 / "vault_pb2.py"]
    materialize(tree, files)
    probe = (
        "from ledger_vault.adapters.grpc._generated.v1 import vault_pb2 as one\n"
        "from ledger_vault.adapters.grpc._generated.v2 import vault_pb2 as two\n"
        "print(one.OpenRequest.DESCRIPTOR.full_name, two.OpenRequest.DESCRIPTOR.full_name)\n"
    )
    assert run_probe(tree / "modules/vault/src", probe) == [
        "ledger.vault.v1.OpenRequest",
        "ledger.vault.v2.OpenRequest",
    ]


def test_generated_files_carry_the_header(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, CONTRACTS)
    files = generated(tree)
    assert len(files) == 8  # types.proto declares no service: it gets no gRPC stubs
    for path, content in files.items():
        if path == PACKAGE / "__init__.py":
            source = "contracts/proto/ledger/vault"
        elif path == V1 / "__init__.py":
            source = "contracts/proto/ledger/vault/v1"
        else:
            source = f"contracts/proto/ledger/vault/v1/{path.name.split('_pb2', 1)[0]}.proto"
        assert content.split(b"\n", 1)[0] == HEADER.format(source).encode(), path
    assert (
        files[V1 / "__init__.py"]
        == (
            HEADER.format("contracts/proto/ledger/vault/v1")
            + '\n"""The gRPC code of module vault\'s contracts, v1."""\n'
        ).encode()
    )


def test_generation_is_deterministic_across_processes(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, CONTRACTS)
    first = generated(tree)
    assert generated(tree) == first
    assert [path for path, content in first.items() if b"\r" in content] == []
    probe = (
        "import hashlib, pathlib, sys\n"
        "from ledger_devtools.protos import generated\n"
        "for path, content in generated(pathlib.Path(sys.argv[1])).items():\n"
        "    print(path.as_posix(), hashlib.sha256(content).hexdigest())\n"
    )
    process = subprocess.run(
        [sys.executable, "-c", probe, str(tree)], capture_output=True, text=True, check=True
    )
    assert process.stdout.splitlines() == [
        f"{path.as_posix()} {hashlib.sha256(content).hexdigest()}" for path, content in first.items()
    ]


