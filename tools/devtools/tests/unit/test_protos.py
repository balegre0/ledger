def test_generated_imports_name_the_module_s_versioned_package(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, CONTRACTS)
    files = generated(tree)
    package = b"from ledger_vault.adapters.grpc._generated.v1 import "
    assert package + b"types_pb2 as " in files[V1 / "vault_pb2.py"]
    assert package + b"types_pb2 as " in files[V1 / "vault_pb2.pyi"]
    assert package + b"vault_pb2 as " in files[V1 / "vault_pb2_grpc.py"]
    assert package + b"vault_pb2 as " in files[V1 / "vault_pb2_grpc.pyi"]
    assert b"'ledger_vault.adapters.grpc._generated.v1.vault_pb2'" in files[V1 / "vault_pb2.py"]
    assert b"from google.protobuf import timestamp_pb2 as " in files[V1 / "vault_pb2.py"]
    by_path = re.compile(rb"ledger\.vault\.v1 import|'ledger\.vault\.v1\.[a-z_]+_pb2'")
    assert [path for path, content in files.items() if by_path.search(content)] == []


def materialize(root: Path, files: Mapping[Path, bytes]) -> None:
    for path, content in files.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_bytes(content)


def run_probe(source: Path, probe: str) -> list[str]:
    process = subprocess.run(
        [sys.executable, "-c", probe],
        env={**os.environ, "PYTHONPATH": str(source)},
        capture_output=True,
        text=True,
        check=False,
    )
    assert (process.returncode, process.stderr) == (0, "")
    return process.stdout.split()


def test_the_generated_code_runs_from_the_module_package(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, CONTRACTS)
    materialize(tree, generated(tree))
    probe = (
        "from ledger_vault.adapters.grpc._generated.v1 import types_pb2, vault_pb2, vault_pb2_grpc\n"
        "request = vault_pb2.OpenRequest(kind=types_pb2.KIND_SEALED)\n"
        "print(type(request).__module__, vault_pb2_grpc.VaultServiceStub.__name__,"
        " vault_pb2.DESCRIPTOR.services_by_name['VaultService'].full_name)\n"
    )
    assert run_probe(tree / "modules/vault/src", probe) == [
        "ledger_vault.adapters.grpc._generated.v1.vault_pb2",
        "VaultServiceStub",
        "ledger.vault.v1.VaultService",
    ]


