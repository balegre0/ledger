# ── generated code only where the gate leaves it unchecked ─────────────────────

PLACED: Final = (
    "lacks the GENERATED header: only `ledger-devtools sync` writes in a generated gRPC package, "
    "which the gate does not check"
)
ELSEWHERE: Final = (
    "generated gRPC code lives only in modules/<module>/src/ledger_<module>/adapters/grpc/_generated: "
    "the gate checks nothing there, and only that"
)


@pytest.mark.parametrize(
    "place",
    [
        "modules/vault/tests/adapters/grpc/_generated",
        "modules/vault/src/other/adapters/grpc/_generated",
        "modules/vault/src/ledger_vault/adapters/grpc/_generated/v1/adapters/grpc/_generated",
        "modules/ghost/src/ledger_ghost/adapters/grpc/_generated",
        "packages/kernel/src/ledger_kernel/adapters/grpc/_generated",
        "apps/api/src/ledger_app_api/adapters/grpc/_generated",
        "tools/devtools/src/ledger_devtools/adapters/grpc/_generated",
    ],
    ids=["tests", "other-package", "nested", "no-module", "package", "app", "tool"],
)
def test_generated_code_outside_a_module_s_package_is_a_problem(tree: Path, vault: Path, place: str) -> None:
    del vault
    write_file(tree, f"{place}/x.py", HEADER.format("contracts/proto/ledger/vault/v1/x.proto") + "\n")
    assert Problem(place, ELSEWHERE) in proto_problems(Workspace.load(tree))


def test_a_hand_written_file_in_the_generated_package_is_a_problem(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/types.proto": TYPES})
    materialize(tree, generated(tree))
    hand_written = {
        # a suppression, spelled apart so the gate's own grep does not find it here
        f"{V1.as_posix()}/helper.py": "from typing import Any\n\nVALUE: Any = 1  # type: " + "ignore[misc]\n",
        f"{V1.as_posix()}/deeper/more.py": '"""Nested."""\n',
    }
    for relative, text in hand_written.items():
        write_file(tree, relative, text)
    assert proto_problems(Workspace.load(tree)) == tuple(
        Problem(path, PLACED) for path in sorted(hand_written)
    )
