type Writer = Callable[[str, str, tuple[str, ...]], Path]

VAULT: Final = """
[package]
name = "vault"
kind = "module"
summary = "Keys."
owners = ["@o"]

[dependencies]
packages = ["kernel", "platform"]
"""
TYPES: Final = """syntax = "proto3";

package ledger.vault.v1;

enum Kind {
  KIND_UNSPECIFIED = 0;
  KIND_SEALED = 1;
}
"""
SERVICE: Final = """syntax = "proto3";

package ledger.vault.v1;

import "google/protobuf/timestamp.proto";

service VaultService {
  rpc Open(OpenRequest) returns (OpenResponse);
}

message OpenRequest {
  google.protobuf.Timestamp at = 1;
}

message OpenResponse {
  string id = 1;
}
"""
TYPED_SERVICE: Final = SERVICE.replace(
    'import "google/protobuf/timestamp.proto";\n',
    'import "google/protobuf/timestamp.proto";\nimport "ledger/vault/v1/types.proto";\n',
).replace("google.protobuf.Timestamp at = 1;\n", "google.protobuf.Timestamp at = 1;\n  Kind kind = 2;\n")
GENERATED: Final = Path("modules/vault/src/ledger_vault/adapters/grpc/_generated")
HEADER: Final = (
    "# GENERATED by ledger-devtools sync from {}: edit the .proto, then run `uv run ledger-devtools sync`."
)


def plant(root: Path, contracts: Mapping[str, str]) -> None:
    for relative, text in contracts.items():
        path = root / "contracts/proto" / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


@pytest.fixture
def vault(write: Writer) -> Path:
    return write("modules/vault", VAULT, ("adapters",))


def test_a_proto_generates_four_files_and_an_init_into_its_module(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/vault.proto": SERVICE})
    names = ("__init__.py", "vault_pb2.py", "vault_pb2.pyi", "vault_pb2_grpc.py", "vault_pb2_grpc.pyi")
    assert list(generated(tree)) == [GENERATED / name for name in names]


def test_a_contract_without_a_service_gets_no_grpc_stubs(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/types.proto": TYPES})
    names = ("__init__.py", "types_pb2.py", "types_pb2.pyi")
    assert list(generated(tree)) == [GENERATED / name for name in names]


def test_generated_imports_name_the_module_package(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/vault.proto": TYPED_SERVICE, "ledger/vault/v1/types.proto": TYPES})
    files = generated(tree)
    package = b"from ledger_vault.adapters.grpc._generated import "
    assert package + b"types_pb2 as " in files[GENERATED / "vault_pb2.py"]
    assert package + b"types_pb2 as " in files[GENERATED / "vault_pb2.pyi"]
    assert package + b"vault_pb2 as " in files[GENERATED / "vault_pb2_grpc.py"]
    assert package + b"vault_pb2 as " in files[GENERATED / "vault_pb2_grpc.pyi"]
    assert b"'ledger_vault.adapters.grpc._generated.vault_pb2'" in files[GENERATED / "vault_pb2.py"]
    assert b"from google.protobuf import timestamp_pb2 as " in files[GENERATED / "vault_pb2.py"]
    by_path = re.compile(rb"ledger\.vault\.v1 import|'ledger\.vault\.v1\.[a-z_]+_pb2'")
    assert [path for path, content in files.items() if by_path.search(content)] == []


def test_the_generated_code_runs_from_the_module_package(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/vault.proto": TYPED_SERVICE, "ledger/vault/v1/types.proto": TYPES})
    for path, content in generated(tree).items():
        (tree / path).parent.mkdir(parents=True, exist_ok=True)
        (tree / path).write_bytes(content)
    probe = (
        "from ledger_vault.adapters.grpc._generated import types_pb2, vault_pb2, vault_pb2_grpc\n"
        "request = vault_pb2.OpenRequest(kind=types_pb2.KIND_SEALED)\n"
        "print(type(request).__module__, vault_pb2_grpc.VaultServiceStub.__name__,"
        " vault_pb2.DESCRIPTOR.services_by_name['VaultService'].full_name)\n"
    )
    process = subprocess.run(
        [sys.executable, "-c", probe],
        env={**os.environ, "PYTHONPATH": str(tree / "modules/vault/src")},
        capture_output=True,
        text=True,
        check=False,
    )
    assert (process.returncode, process.stderr) == (0, "")
    assert process.stdout.split() == [
        "ledger_vault.adapters.grpc._generated.vault_pb2",
        "VaultServiceStub",
        "ledger.vault.v1.VaultService",
    ]


def test_generated_files_carry_the_header(tree: Path, vault: Path) -> None:
    del vault
    plant(tree, {"ledger/vault/v1/vault.proto": TYPED_SERVICE, "ledger/vault/v1/types.proto": TYPES})
    files = generated(tree)
    assert len(files) == 7  # types.proto declares no service: it gets no gRPC stubs
    for path, content in files.items():
        stem = path.name.split("_pb2", 1)[0]
        source = (
            "contracts/proto/ledger/vault"
            if path.name == "__init__.py"
            else f"contracts/proto/ledger/vault/v1/{stem}.proto"
        )
        assert content.split(b"\n", 1)[0] == HEADER.format(source).encode(), path
    assert (
        files[GENERATED / "__init__.py"]
        == (
            HEADER.format("contracts/proto/ledger/vault")
            + '\n"""The gRPC code of module vault\'s contract."""\n'
        ).encode()
    )


