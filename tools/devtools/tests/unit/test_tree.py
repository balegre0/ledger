"""The repository's files as git sees them: devtools never reads what ``.gitignore`` leaves out."""

from pathlib import Path

from ledger_devtools.cli import main
from ledger_devtools.images import dockerfiles
from ledger_devtools.tree import scan, visible_files
from ledger_devtools.workspace import Workspace

UNREADABLE = b"TZif2\x00\x00\xff\xfe\x80 binary, not UTF-8"


def put(root: Path, relative: str, content: bytes = b"x\n") -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)


def test_ignored_files_and_directories_and_git_s_own_are_left_out(tmp_path: Path) -> None:
    put(tmp_path, ".gitignore", b".venv\nbuild/\n*.p12\n!keep.p12\n")
    put(tmp_path, "a/kept.txt")
    put(tmp_path, "a/.venv/lib/UTC", UNREADABLE)
    put(tmp_path, "a/build/out.txt")
    put(tmp_path, "a/secret.p12")
    put(tmp_path, ".git/HEAD")
    put(tmp_path, "b/.gitignore", b"local.txt\n")
    put(tmp_path, "b/local.txt")
    put(tmp_path, "b/shared.txt")
    put(tmp_path, "local.txt")  # b's .gitignore applies under b only
    assert visible_files(tmp_path) == (
        Path(".gitignore"),
        Path("a/kept.txt"),
        Path("b/.gitignore"),
        Path("b/shared.txt"),
        Path("local.txt"),
    )
    assert scan(tmp_path).directories == (Path("a"), Path("b"))


def test_a_tree_without_a_gitignore_leaves_out_git_s_own_only(tmp_path: Path) -> None:
    put(tmp_path, ".git/config")
    put(tmp_path, "x/y.txt")
    assert visible_files(tmp_path) == (Path("x/y.txt"),)


def test_a_nested_repository_or_worktree_is_left_out_as_git_leaves_it(tmp_path: Path) -> None:
    put(tmp_path, "kept.txt")
    put(tmp_path, "vendor/lib/.git/HEAD")  # a repository of its own
    put(tmp_path, "vendor/lib/code.py")
    put(tmp_path, ".claude/worktrees/other/.git", b"gitdir: ../../../.git/worktrees/other\n")  # a worktree
    put(tmp_path, ".claude/worktrees/other/modules/m/manifest.toml", UNREADABLE)
    assert visible_files(tmp_path) == (Path("kept.txt"),)
    assert scan(tmp_path).directories == (
        Path(".claude"),
        Path(".claude/worktrees"),
        Path("vendor"),
    )


def test_devtools_never_reads_an_ignored_manifest_or_dockerfile(tree: Path) -> None:
    put(tree, ".gitignore", b".venv\nbuild/\n")
    put(tree, "tools/build/manifest.toml", UNREADABLE)  # tools/* would match it
    put(tree, "packages/.venv/manifest.toml", UNREADABLE)
    put(tree, "deploy/build/Dockerfile", b"FROM python:latest\n")
    put(tree, "deploy/local/.venv/lib/tzdata/UTC", UNREADABLE)
    put(tree, "apps/build/pyproject.toml", b"# GENERATED by ledger-devtools sync from manifest.toml\n")
    assert {package.name for package in Workspace.load(tree).packages} == {
        "kernel",
        "platform",
        "identity",
        "api",
    }
    assert dockerfiles(tree) == []
    assert main(["sync", "--root", str(tree)]) == 0
    assert main(["check", "--root", str(tree)]) == 0
    assert (tree / "apps/build/pyproject.toml").is_file()  # an ignored file is never an orphan to delete
