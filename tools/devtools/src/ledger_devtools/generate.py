"""What ``sync`` writes: each file derived from the manifests (§4.7).

Text is built deterministically (sorted, stable), so ``check`` can compare it with what is on disk. Python
is written the way ``ruff format`` writes it (every collection exploded, one item per line, with a trailing
comma, which ruff keeps; strings quoted as ruff quotes them and wrapped to the line length), so a generated
module passes the gate as written.
"""

